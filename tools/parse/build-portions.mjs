// Extracts the curated portion weights the SFT generator already maintains into
// a runtime lookup table (tools/parse/portions.json).
//
// generate-synthetic.mjs carries two sets of hand-curated, DB-verified weights:
//   POOLS[*].units[kind='count']  grams of ONE piece   (nugget 16 g, oreo 11 g)
//   FRACTION_DISHES               grams of a WHOLE dish (lasagna 1300-1500 g)
// Today they exist only to render training text, so the numbers reach the app
// exclusively as something the model memorized — and the v9 gate shows that
// channel is lossy: the model returned 111 g per McNugget (a whole serving) and
// 143 g for a whole lasagna pan, despite being trained on 16 g and ~1400 g.
//
// The values are already correct and already maintained. Reading them directly
// is strictly better than hoping a 0.8B network reproduces them, so this script
// lifts them out mechanically. It parses the generator's SOURCE rather than
// importing it, because importing runs a full 40k generation as a side effect.
//
// Re-run after changing pool weights:
//   node tools/parse/build-portions.mjs
//
// Single source of truth stays generate-synthetic.mjs; portions.json is a build
// artifact. tools/parse/portions.test.mjs asserts the two agree.

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = join(HERE, '..', '..');
const SRC = readFileSync(join(ROOT, 'tools/finetune/generate-synthetic.mjs'), 'utf8');

// ---- per-piece weights from POOLS ------------------------------------------
// { q: 'chicken nuggets', name: 'chicken nuggets', units: [{ kind: 'count', unit: 'nugget', g: 16, ... }] }
const pieces = {};
const poolRe = /\{\s*q:\s*'([^']+)',\s*name:\s*'([^']+)',\s*units:\s*\[([\s\S]*?)\]\s*\}/g;
for (const m of SRC.matchAll(poolRe)) {
  const [, q, name, units] = m;
  const cm = units.match(/\{\s*kind:\s*'count',\s*unit:\s*'([^']+)',\s*g:\s*(\d+(?:\.\d+)?)/);
  if (!cm) continue;
  const [, unit, g] = cm;
  // Later pools may repeat a name (potstickers/dumplings share a DB row); first
  // definition wins, matching the generator's own pick order closely enough for
  // a weight lookup.
  if (!(name in pieces)) pieces[name] = { unit, grams: Number(g), q };
}

// ---- whole-dish weights from FRACTION_DISHES -------------------------------
// { q: 'lasagna', name: 'lasagna', wholeMin: 1300, wholeMax: 1500, meal: 'dinner' }
const dishes = {};
const dishRe = /\{\s*q:\s*'([^']+)',\s*name:\s*'([^']+)',\s*wholeMin:\s*(\d+),\s*wholeMax:\s*(\d+)/g;
for (const m of SRC.matchAll(dishRe)) {
  const [, q, name, lo, hi] = m;
  dishes[name] = { grams: Math.round((Number(lo) + Number(hi)) / 2), q };
}

if (Object.keys(pieces).length < 15) throw new Error(`only ${Object.keys(pieces).length} piece weights parsed — pool format changed?`);
if (Object.keys(dishes).length < 5) throw new Error(`only ${Object.keys(dishes).length} dish weights parsed — FRACTION_DISHES format changed?`);

const out = { _source: 'generated by tools/parse/build-portions.mjs from generate-synthetic.mjs', pieces, dishes };
writeFileSync(join(HERE, 'portions.json'), `${JSON.stringify(out, null, 2)}\n`);

// The app cannot import from tools/, so emit a typed module into the mobile
// tree from the SAME parse. Generated, never hand-edited — re-run this script.
const ts = `// GENERATED by tools/parse/build-portions.mjs — do not edit by hand.
//
// Curated portion weights lifted from the SFT generator's pools
// (tools/finetune/generate-synthetic.mjs), which are hand-checked against
// foods.db. These are the same numbers the estimator was TRAINED on; reading
// them directly beats hoping a 0.8B network reproduced them. The v9 gate showed
// that channel is lossy — the model returned 111 g per McNugget (a whole
// serving) and 143 g for a whole lasagna pan, against training values of 16 g
// and ~1400 g.
//
// Regenerate after changing pool weights:  node tools/parse/build-portions.mjs

/** Grams of ONE piece of a countable food. */
export const PIECE_GRAMS: Record<string, { unit: string; grams: number }> = ${
  JSON.stringify(Object.fromEntries(Object.entries(pieces).map(([k, v]) => [k, { unit: v.unit, grams: v.grams }])), null, 2)
};

/** Grams of a WHOLE dish, for "half a pizza" / "a quarter of the lasagna". */
export const DISH_GRAMS: Record<string, { grams: number }> = ${
  JSON.stringify(Object.fromEntries(Object.entries(dishes).map(([k, v]) => [k, { grams: v.grams }])), null, 2)
};
`;
writeFileSync(join(ROOT, 'mobile/src/lib/ai/portions.ts'), ts);

console.log(`wrote portions.json + mobile/src/lib/ai/portions.ts: ${Object.keys(pieces).length} per-piece weights, ${Object.keys(dishes).length} whole-dish weights`);
for (const [k, v] of Object.entries(pieces)) console.log(`  piece ${k.padEnd(24)} ${v.grams} g/${v.unit}`);
for (const [k, v] of Object.entries(dishes)) console.log(`  dish  ${k.padEnd(24)} ${v.grams} g whole`);
